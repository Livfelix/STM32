from pathlib import Path
import argparse
from PIL import Image, ImageDraw, ImageFont
parser=argparse.ArgumentParser(description='Generate compact6x10 ASCII; bit7=left.')
parser.add_argument('--font',default='C:/Windows/Fonts/consola.ttf')
args=parser.parse_args()
font=ImageFont.truetype(args.font,10)
rows=[]
for code in range(32,128):
    image=Image.new('L',(6,10))
    ImageDraw.Draw(image).text((0,-2),chr(code),font=font,fill=255)
    rows.append([sum((image.getpixel((x,y))>=90)<<(7-x) for x in range(6)) for y in range(10)])
assert len(rows)==96 and any(rows[ord('A')-32]) and all(value&3==0 for row in rows for value in row)
output=Path(__file__).resolve().parent.parent/'src/font.c'
output.write_text('/* Generated by tools/gen_font.py; bit7=left,6x10. */\n#include "font.h"\nconst uint8_t font6x10[96][10] = {\n'+'\n'.join('  {'+','.join(f'0x{v:02X}' for v in row)+'}, /* ASCII'+str(code)+' */' for code,row in enumerate(rows,32))+'\n};\n',encoding='utf-8')
print('font.c:96 glyphs,960 bytes,6x10')
